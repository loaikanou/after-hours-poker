const messages: Record<Locale, Record<MessageKey, string>> = { en, ar };

export function translate(locale: Locale, key: MessageKey): string {
  return messages[locale][key] ?? en[key];
}

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;

export function translator(locale: Locale): Translate {
  return (key, values) => (values ? fill(translate(locale, key), values) : translate(locale, key));
}

/** Turn a structured table event into a localized sentence. */
export function describeEvent(event: TableEvent, t: Translate, locale: Locale): string {
  const values = {
    name: event.name ?? "",
    amount: event.amount === undefined ? "" : formatNumber(event.amount, locale),
    suit: event.suit ?? "",
    team: event.team === undefined ? "" : formatNumber(event.team, locale),
    names: (event.names ?? []).join(" & "),
    card: event.card ? `${rankName(event.card.rank)}${event.card.suit}` : "",
    contract: event.contract ? t(contractKeys[event.contract]) : "",
    hand: event.hand ? t(`hand_${event.hand}` as MessageKey) : "",
  };
  if (event.kind === "tarneebHand") return t(event.made ? "event_tarneebMade" : "event_tarneebSet", values);
  return t(`event_${event.kind}` as MessageKey, values);
}

/** Map any thrown value (usually a ConvexError with a code) to a localized message. */
export function errorMessage(error: unknown, t: Translate, locale: Locale): string {
  if (error instanceof ConvexError) {
    const data = error.data as Partial<GameErrorData>;
    const code = data?.code as ErrorCode | undefined;
    if (code && `error_${code}` in en) {
      return t(`error_${code}` as MessageKey, { amount: data.amount === undefined ? "" : formatNumber(data.amount, locale) });
    }
  }
  if (error instanceof Error && error.message === "addName") return t("error_addName");
  return t("error_generic");
}
